'use strict';
// pcbridge/ScreenerBridge/pattern_registry.py (the ONE source of the bullish pattern engine's 194 patterns + the owner's own)
// -> web/data/pattern-registry.js (window.SB_PATTERNS: the Backtest Lab's Pattern Library list) and docs/PATTERN_SPECS.md
// (the written rules). Run after every registry change: `npm run patterns` (tests/pcbridge-patterns.test.js fails while either
// copy is out of date). Needs python3.
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const REG = path.join(ROOT, 'pcbridge', 'ScreenerBridge', 'pattern_registry.py');
const OUT_JS = path.join(ROOT, 'web', 'data', 'pattern-registry.js');
const OUT_MD = path.join(ROOT, 'docs', 'PATTERN_SPECS.md');

function python() {
  return ['python3', 'python'].find((p) => spawnSync(p, ['--version']).status === 0);
}

function load() {
  const py = python();
  if (!py) throw new Error('python3 is needed to read the pattern registry');
  const r = spawnSync(py, [REG, 'json'], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(r.stderr || 'pattern_registry.py failed');
  return JSON.parse(r.stdout);
}

function renderJs(reg) {
  return '/* Generated by tools/build_patterns.js from pcbridge/ScreenerBridge/pattern_registry.py - do not edit by hand. */\n' +
    'window.SB_PATTERNS = ' + JSON.stringify(reg) + ';\n';
}

const cell = (s) => String(s == null ? '' : s).replace(/\|/g, '/');

function renderMd(reg) {
  const ps = reg.patterns;
  const count = (st) => ps.filter((p) => p.status === st && p.category !== 'X').length;
  const out = ['# Pattern specifications (bullish pattern engine)', '',
    'Generated by `npm run patterns` from `pcbridge/ScreenerBridge/pattern_registry.py` - do not edit by hand. The plan: docs/PATTERN_ENGINE_PLAN.md.', '',
    'Master prompt patterns: ' + ps.filter((p) => p.category !== 'X').length + ' - ' +
      Object.keys(reg.statusNames).filter((st) => count(st)).map((st) => reg.statusNames[st] + ' ' + count(st)).join(', ') + '.', '',
    'Status: **Implemented** = built in the new engine with written rules and tests, usable in the Backtest Lab (Pattern "Pattern library"); ' +
      '**In the Lab (own group)** = usable through an existing Lab Pattern; **Partial** = a Lab filter or only in the sheet / website; ' +
      '**Planned** = no rules yet; **Data limited** = the data cannot test it properly.', ''];
  Object.keys(reg.categories).forEach((cat) => {
    const rows = ps.filter((p) => p.category === cat);
    if (!rows.length) return;
    out.push('## ' + cat + '. ' + reg.categories[cat], '', '| ID | Pattern | Status | Family | Data | Note |', '|---|---|---|---|---|---|');
    rows.forEach((p) => out.push('| ' + [p.id, p.name, p.status === 'implemented' ? '**' + p.statusName + '**' : p.statusName, p.family,
      p.needs, p.note].map(cell).join(' | ') + ' |'));
    out.push('');
  });
  out.push('Data: o = OHLC, v = volume, b = a benchmark index, i = intraday candles.', '', '## Rules of the implemented patterns', '');
  ps.filter((p) => p.status === 'implemented').forEach((p) => {
    out.push('### ' + p.id + ' ' + p.name + ' (version ' + p.version + ')', '',
      'Timeframes: ' + p.timeframes.join(' / ') + ' - parameters: ' +
        Object.keys(p.params).map((k) => '`' + k + '` ' + p.params[k]).join(', '), '');
    p.rules.forEach((r, i) => out.push((i + 1) + '. ' + r));
    out.push('');
  });
  return out.join('\n');
}

if (require.main === module) {
  const reg = load();
  fs.writeFileSync(OUT_JS, renderJs(reg));
  fs.writeFileSync(OUT_MD, renderMd(reg));
  console.log('patterns: ' + path.relative(ROOT, OUT_JS) + ' + ' + path.relative(ROOT, OUT_MD) + ' (' + reg.patterns.length + ' entries)');
}
module.exports = { load, renderJs, renderMd, OUT_JS, OUT_MD };
