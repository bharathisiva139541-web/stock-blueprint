'use strict';
// tradingview/StockBlueprint_CHoCH_FVG.pine -> web/data/pine-template.js (window.SB_PINE_SRC): the Backtest Lab page's
// "Copy TradingView script" button fills the script's inputs with the form's rules (web/lib/pine.js). Run after every
// change of the .pine: `npm run pine` (tests/tradingview-pine.test.js fails while the copy is out of date).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'tradingview', 'StockBlueprint_CHoCH_FVG.pine');
const OUT = path.join(ROOT, 'web', 'data', 'pine-template.js');

function render(src) {
  return '/* Generated by tools/build_pine.js from tradingview/StockBlueprint_CHoCH_FVG.pine - do not edit by hand. */\n' +
    'window.SB_PINE_SRC = ' + JSON.stringify(src) + ';\n';
}
if (require.main === module) {
  fs.writeFileSync(OUT, render(fs.readFileSync(SRC, 'utf8')));
  console.log('pine: ' + path.relative(ROOT, OUT));
}
module.exports = { render, SRC, OUT };
