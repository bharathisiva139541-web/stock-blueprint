#!/usr/bin/env node
/*
 * Profile every worksheet of a downloaded Stock Blueprint workbook and write
 * the public summary used by the website's Excel page:
 *
 *     node tools/analyze_workbook.js "Copy of Stock Blueprint.xlsx" [out.js] [--max-rows N]
 *
 * Default output: web/data/workbook-analysis.js  (sets window.SB_WORKBOOK).
 *
 * The output is PUBLIC (the repo and site are public), so it runs with
 * publicMode: personal sheets (Portfolio, Risk Manager, Control Panel, Trade
 * Log, Trade Dashboard, anything with qty / capital / P&L / e-mails) keep only
 * their structure, personal columns elsewhere are redacted, and the file is
 * refused if an e-mail address would still end up in it.
 * The master (SYMBOL -> sector / industry / basic industry) comes from the
 * 'Main' tab (headers on row 2).
 */
'use strict';

const fs = require('fs');
const path = require('path');
const xlsx = require('../web/lib/xlsx-reader.js');
const wa = require('../web/lib/workbook-analysis.js');

const EMAIL_RE = /[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}/;
const DEFAULT_OUT = path.join(__dirname, '..', 'web', 'data', 'workbook-analysis.js');

/** 'YYYY-MM-DD HH:MM' in Asia/Kolkata. */
function istStamp(date) {
  const parts = {};
  new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Kolkata', year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', hourCycle: 'h23'
  }).formatToParts(date).forEach(function (p) { parts[p.type] = p.value; });
  return parts.year + '-' + parts.month + '-' + parts.day + ' ' + parts.hour + ':' + parts.minute;
}

function parseArgs(argv) {
  const args = { file: null, out: DEFAULT_OUT, maxRows: 200000 };
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--max-rows') args.maxRows = Number(argv[++i]);
    else if (argv[i] === '-h' || argv[i] === '--help') args.help = true;
    else rest.push(argv[i]);
  }
  args.file = rest[0] || null;
  if (rest[1]) args.out = path.resolve(rest[1]);
  return args;
}

/** Throws when the public payload could leak personal data. */
function privacyCheck(payload, json) {
  if (EMAIL_RE.test(json)) throw new Error('refusing to write: the output still contains an e-mail address');
  payload.sheets.forEach(function (s) {
    if (s.personal && !s.publicStructureOnly) throw new Error('refusing to write: personal sheet "' + s.name + '" is not structure-only');
    if (!s.personal || !s.blocks) return;
    s.blocks.forEach(function (b) {
      if (b.title || b.reconciliation || b.industryDistribution || b.sectorDistribution) {
        throw new Error('refusing to write: personal sheet "' + s.name + '" carries values');
      }
      b.columns.forEach(function (c) {
        if (c.samples || c.min != null || c.max != null || c.minDate || (c.formula && c.formula.example)) {
          throw new Error('refusing to write: personal sheet "' + s.name + '" column ' + c.letter + ' carries values');
        }
      });
    });
  });
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help || !args.file) {
    console.log('usage: node tools/analyze_workbook.js <file.xlsx> [out.js] [--max-rows N]');
    process.exit(args.help ? 0 : 2);
  }
  const t0 = Date.now();
  const buf = fs.readFileSync(args.file);
  const stat = fs.statSync(args.file);
  const wb = await xlsx.readWorkbook(buf, { maxRowsPerSheet: args.maxRows > 0 ? args.maxRows : 200000 });
  const t1 = Date.now();

  const mainSheet = wb.sheets.find(function (s) { return s.name.toLowerCase() === 'main'; });
  const master = mainSheet ? wa.buildMaster(mainSheet) : null;
  if (!mainSheet) console.warn('warning: no "Main" sheet - symbols are not reconciled');

  const res = wa.analyzeWorkbook(wb, { master: master, publicMode: true, maxSamples: 5, maxDistinct: 30, maxList: 30 });
  if (!res.ok) throw new Error(res.reason);

  const payload = Object.assign({
    generated: istStamp(new Date()),
    source: path.basename(args.file).replace(EMAIL_RE, '[email]'),
    sourceModified: istStamp(stat.mtime),
    state: 'CACHED',
    publicMode: true
  }, res);
  const json = JSON.stringify(payload);
  privacyCheck(payload, json);

  const text = '// Generated by tools/analyze_workbook.js - do not edit by hand.\n' +
    '// Public workbook profile: personal sheets are structure-only, personal columns redacted, e-mails masked.\n' +
    'window.SB_WORKBOOK = ' + json + ';\n';
  fs.mkdirSync(path.dirname(args.out), { recursive: true });
  const tmp = args.out + '.tmp';
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, args.out);

  const s = res.summary;
  console.log('read ' + wb.sheets.length + ' sheets in ' + (t1 - t0) + ' ms, analyzed in ' + (Date.now() - t1) + ' ms');
  console.log('master symbols: ' + (master ? Object.keys(master).length : 0));
  console.log('rows: ' + s.totalRows + ', data rows: ' + s.totalDataRows + ', formulas: ' + s.totalFormulaCells + ', error cells: ' + s.totalErrorCells);
  console.log('personal (structure only): ' + (s.personalSheets.join(', ') || 'none'));
  wb.warnings.forEach(function (w) { console.log('warning: ' + w); });
  console.log('wrote ' + path.relative(process.cwd(), args.out) + ' (' + Math.round(text.length / 1024) + ' KB)');
}

main().catch(function (e) {
  console.error('error: ' + (e && e.message ? e.message : e));
  process.exit(1);
});
