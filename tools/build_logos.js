'use strict';
// Company logos for the website (owner, 02-Nov-2026: "use the best free source to update logos in our website").
// Source: github.com/dharunashokkumar/indian-listed-company-logos - data/logos/nse/NSE_<TICKER>.svg (3,083 NSE logos,
// collected from TradingView; the logos are trademarks of their companies) + data/logos/metadata.json (company name,
// old tickers). The image files are NOT copied into this repo: web/data/logos.js only lists which NSE symbols have a
// logo and the two addresses that serve that exact version (jsDelivr's CDN first, GitHub's raw files as the backup);
// web/ui/core.js logoHtml builds the <img> and falls back to the two-letter monogram.
//
//   git clone --depth 1 https://github.com/dharunashokkumar/indian-listed-company-logos ../indian-listed-company-logos
//   npm run logos -- ../indian-listed-company-logos            (or: node tools/build_logos.js <that folder>)
//
// TradingView writes '_' where NSE writes '-' (BAJAJ_AUTO = BAJAJ-AUTO); the browser tries both. Old tickers from the
// metadata (HEG -> HEGAM ...) are kept as aliases when they point at one company only.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const REPO = 'dharunashokkumar/indian-listed-company-logos';

/** The logos.js text for a checkout: { text, tickers, aliases, commit } (pure - tests call it on a fixture folder). */
function buildLogos(dir, commit, today) {
  const nseDir = path.join(dir, 'data', 'logos', 'nse');
  if (!fs.existsSync(nseDir)) throw new Error('no data/logos/nse in ' + dir + ' - is it a checkout of ' + REPO + '?');
  if (!/^[0-9a-f]{40}$/.test(commit || '')) throw new Error('need the full 40-character commit of the checkout, got "' + commit + '"');
  const tickers = fs.readdirSync(nseDir)
    .map((f) => /^NSE_(.+)\.svg$/.exec(f))
    .filter((m) => m && /^[A-Z0-9&_.-]{1,30}$/.test(m[1]))
    .map((m) => m[1])
    .sort();
  const have = new Set(tickers);
  const aliases = {};
  const metaPath = path.join(dir, 'data', 'logos', 'metadata.json');
  if (fs.existsSync(metaPath)) {
    const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
    const seen = {};
    (meta.logos || []).forEach((x) => {
      if (!x || x.exchange !== 'NSE' || !have.has(x.ticker)) return;
      (x.aliases || []).forEach((a) => {
        const old = String(a).replace(/^NSE:/, '').toUpperCase();
        if (!/^[A-Z0-9&_.-]{1,30}$/.test(old) || have.has(old)) return;   // a ticker with its own logo wins
        (seen[old] = seen[old] || new Set()).add(x.ticker);
      });
    });
    Object.keys(seen).sort().forEach((old) => { if (seen[old].size === 1) aliases[old] = [...seen[old]][0]; });
  }
  const source = {
    name: 'Indian listed company logos (collected from TradingView; trademarks of their companies)',
    repo: 'https://github.com/' + REPO,
    commit: commit,
    built: today,
    count: tickers.length,
    // tried in this order; the file name is NSE_<ticker>.svg
    urls: ['https://cdn.jsdelivr.net/gh/' + REPO + '@' + commit + '/data/logos/nse/',
           'https://raw.githubusercontent.com/' + REPO + '/' + commit + '/data/logos/nse/']
  };
  const text = '// Generated by tools/build_logos.js (npm run logos -- <checkout>) - do not edit by hand.\n' +
    '// Company logos: NSE symbol -> NSE_<ticker>.svg of ' + source.repo + ' at commit ' + commit + ',\n' +
    '// loaded from the addresses below (the images are not copied here). Logos are trademarks of their companies.\n' +
    '// A symbol without a logo shows a neutral two-letter monogram (web/ui/core.js logoHtml).\n' +
    'window.SB_LOGO_SOURCE = ' + JSON.stringify(source) + ';\n' +
    'window.SB_LOGO_TICKERS = ' + JSON.stringify(tickers.join(' ')) + ';\n' +
    'window.SB_LOGO_ALIASES = ' + JSON.stringify(aliases) + ';\n' +
    '// Hand-checked exceptions (they win over the list above): \'NSE:SYMBOL\' -> { url, source, verified: true }\n' +
    'window.SB_LOGOS = {};\n';
  return { text, tickers, aliases, commit };
}

function main(argv) {
  const dir = argv[2];
  if (!dir) {
    console.error('usage: node tools/build_logos.js <checkout of ' + REPO + '> [commit]');
    return 2;
  }
  const commit = argv[3] || execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const out = buildLogos(dir, commit, new Date().toISOString().slice(0, 10));
  const file = path.join(__dirname, '..', 'web', 'data', 'logos.js');
  fs.writeFileSync(file, out.text);
  console.log('web/data/logos.js: ' + out.tickers.length + ' NSE logos, ' + Object.keys(out.aliases).length + ' old tickers, commit ' +
              commit.slice(0, 12) + ' (' + Math.round(out.text.length / 1024) + ' KB)');
  return 0;
}

module.exports = { buildLogos };
if (require.main === module) process.exitCode = main(process.argv);
